// 随机选择话术
const getRandomCommentary = (type: keyof typeof FALLBACK_COMMENTARY): string => {
  const commentaries = FALLBACK_COMMENTARY[type];
  return commentaries[Math.floor(Math.random() * commentaries.length)];
};

// 导出函数：获取环境氛围话术（用于自动轮播）
export const getAmbientCommentary = (): string => {
  return getRandomCommentary('ambient');
};

// 检查是否配置了API Key
const isApiConfigured = (): boolean => {
  return !!(process.env.API_KEY && process.env.API_KEY.trim() !== "");
};

let ai: GoogleGenAI | null = null;

// 延迟初始化AI实例
const getAI = (): GoogleGenAI | null => {
  if (!isApiConfigured()) {
    return null;
  }
  if (!ai) {
    ai = new GoogleGenAI({ apiKey: process.env.API_KEY || "" });
  }
  return ai;
};

export const getSheepCommentary = async (status: 'lost' | 'start' | 'stuck'): Promise<string> => {
  // 如果没有配置API Key，直接使用备选话术
  if (!isApiConfigured()) {
    console.log("API Key not configured, using fallback commentary");
    return getRandomCommentary(status);
  }

  try {
    const aiInstance = getAI();
    if (!aiInstance) {
      return getRandomCommentary(status);
    }

    const prompt = status === 'lost' 
      ? "玩家在探险中氧气耗尽（输了）。给一句幽默感十足的、带点科技感的嘲讽。使用深海相关的谐音梗。"
      : status === 'start'
      ? "玩家开始了深海遗迹探索。用冷酷的AI语调提醒他们成功回收遗迹的概率不到0.1%。"
      : "玩家卡住了。给一个充满神秘感的探测提示。";

    const response = await aiInstance.models.generateContent({
      model: 'gemini-3-flash-preview',
      contents: prompt,
      config: {
        systemInstruction: "你是一个名为'深蓝'的遗迹探索助手AI。你说话冷静但带有一丝毒舌和幽默，喜欢用潜水术语和数据分析的语气。",
        temperature: 0.9,
      }
    });

    const text = response.text?.trim();
    
    // 如果AI返回空内容，使用备选话术
    if (!text) {
      console.log("AI returned empty response, using fallback");
      return getRandomCommentary(status);
    }

    return text;
  } catch (error) {
    console.error("Gemini Error:", error);
    // 发生错误时使用备选话术
    return getRandomCommentary(status);
  }
};
